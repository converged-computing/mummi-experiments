import argparse
import struct

def get_xtc_ns(xtc_file: str) -> float:
    """
    This (magic) function returns the length in nanoseconds of a given .xtc
    """
    try:
        with open(xtc_file, 'rb') as f:
            tag = f.read(8)                           # Tag: magic number and number of atoms
            n = 92 + struct.unpack(">l", f.read(84)[-4:])[0]  # Size of frame in bytes

            f.seek(int(-5*n/4), 2)                    # This should contain a complete frame
            frame = f.read()                          # Read the remaining part in
            n = frame.index(tag)                      # Find the tag

            return 0.001*struct.unpack(">f",frame[n+12:n+16])[0]
    except Exception as e:
        print(e)
        return -1

def mda_get_xtc_ns(xtc_file: str) -> float:
    """
    Return the length in nanoseconds of a given .xtc

    It requires the package MDAnalysis
    """
    import MDAnalysis as mda
    u = mda.Universe("lipids-water-eq6.gro", xtc_file)
    ts_unit = u.trajectory.units["time"]
    if ts_unit == "ps":
        # it's in picosecond
        unit = 1000.0
    elif ts_unit == "ns":
        unit = 1
    else:
        print(f"Unknown units: {ts_unit}")

    return u.trajectory.totaltime / unit

def main(args):
    try:
        # Note that MDAnalysis is slow to load
        # the magic function is much faster than the (more reliable) function using MDAnalysis
        import MDAnalysis as mda
        for f in args.xtc:
            print(f"{f:20s} => {get_xtc_ns(f)} ns | {mda_get_xtc_ns(f)} ns")

    except:
        for f in args.xtc:
            print(f"{f:20s} => {get_xtc_ns(f)} ns")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description = "Script that reads XTC files generated by GROMACS and prints their simulated durations")
    parser.add_argument("-x", "--xtc", help = "XTC files (can use *.xtc)", required = True, nargs = '+')
    args = parser.parse_args()

    main(args)
